export type DatasetTarget = "sold_units" | "item_line_count";
export type MeasurementUnit = "physical_unit" | "item_line";
export type EvaluationApplicability = {
  applicable: boolean;
  reason: string | null;
  evaluated_horizon_days: number | null;
  requested_horizon_days: number;
};
export type Item = {
  evaluation_applicability?: EvaluationApplicability;
  product_id: string;
  name: string;
  batch_size: number;
  max_daily_qty: number;
  forecast_mean: number | null;
  recommended_qty: number;
  confirmed_qty: number | null;
  method: string;
  diagnostic_method?: string;
  target_is_open?: boolean;
  active_from?: string | null;
  active_to?: string | null;
  automatic_eligible?: boolean;
  model_id?: string | null;
  fallback_reason?: string | null;
  warnings: string[];
  used_dates?: string[];
  n?: number;
};
export type PlanSummary = {
  id: string;
  revision: number;
  status: string;
  dataset_id: string;
  target_date: string;
  source: string;
  created_at?: string;
};
export type Plan = PlanSummary & {
  items: Item[];
  cutoff: string;
  requested_method?: string;
  dataset_version?: string;
  bakery_id?: string;
  mode?: string;
  model_id?: string | null;
  model_version?: string;
  protocol_version?: string;
  target?: DatasetTarget;
  unit?: MeasurementUnit;
};
export type Dataset = {
  id: string;
  source: string;
  row_count?: number;
  rows?: { date: string }[];
  created_at?: string;
  missing_calendar_days?: number | null;
  stockout_count?: number | null;
  unknown_stockout_count?: number | null;
  diagnostics?: string[];
  bakery_id: string;
  target: DatasetTarget;
  unit: MeasurementUnit;
  provenance: string;
  schema_version: string;
  dataset_version?: string;
  version?: string;
  metadata_declared?: boolean;
};
export type ModelSummary = {
  id: string;
  status: "ready" | "not_ready";
  reason?: string | null;
  training_cutoff: string;
  target: DatasetTarget;
  unit: MeasurementUnit;
  bakery_id: string;
  dataset_id: string;
  dataset_version: string;
  protocol_version: string;
  evaluation?: {
    protocol?: string;
    experimental?: boolean;
    horizon_days?: number;
    feature_cutoff_policy?: string;
    first_holdout_cutoff?: string | null;
    embargoed_dates?: string[];
    coverage_denominator?: string;
    coverage_denominator_n?: number;
    paired_dates?: string[];
    paired_date_count?: number;
    paired_start?: string | null;
    paired_end?: string | null;
    paired_n?: number;
    b1_mae?: number | null;
    ml_mae?: number | null;
    coverage?: number;
    fit_end?: string | null;
    holdout_start?: string | null;
    holdout_end?: string | null;
  };
  products: Record<string, { status: string; reason?: string | null }>;
};
export type Forecast = {
  evaluation_applicability?: EvaluationApplicability;
  dataset_id: string;
  bakery_id: string;
  target: DatasetTarget;
  unit: MeasurementUnit;
  model_id: string | null;
  items: {
    evaluation_applicability?: EvaluationApplicability;
    product_id: string;
    forecast_mean: number | null;
    b1_mean: number | null;
    method: string;
    fallback_reason?: string | null;
    used_dates?: string[];
    n?: number;
  }[];
};
